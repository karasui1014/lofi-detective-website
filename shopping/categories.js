/* 品名からカテゴリIDを推定する。
   一致するキーワードのうち最も長いものを優先（誤判定を減らす）。 */
window.guessCategory = function (rawName) {
  const name = String(rawName || '').trim().toLowerCase();
  if (!name) return 'other';
  let best = null;
  let bestLen = 0;
  for (const catId in window.ITEM_DICTIONARY) {
    for (const kw of window.ITEM_DICTIONARY[catId]) {
      if (name.includes(kw.toLowerCase()) && kw.length > bestLen) {
        best = catId;
        bestLen = kw.length;
      }
    }
  }
  return best || 'other';
};

/* 予測入力の初期シード（catalog が空のときの候補）。
   辞書の品名を重複なくフラットにして返す。 */
window.seedItemNames = function () {
  const seen = new Set();
  const out = [];
  for (const catId in window.ITEM_DICTIONARY) {
    for (const kw of window.ITEM_DICTIONARY[catId]) {
      // 「○○」のような曖昧語はサジェスト種から除外
      if (['肉', '魚', '野菜', '果物', '冷凍', 'お菓子', '飲料', '掃除', '化粧', '薬', '乾物', '缶詰', 'カレー'].includes(kw)) continue;
      if (!seen.has(kw)) { seen.add(kw); out.push({ name: kw, category: catId }); }
    }
  }
  return out;
};
